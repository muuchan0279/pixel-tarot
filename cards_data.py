def all_cards() -> list[dict]:
    cards = []
    for i, (en, ja, up, rev) in enumerate(MAJOR):
        cards.append({"id": f"m{i:02d}", "en": en, "ja": ja, "up": up, "rev": rev, "major": True})
    for suit, rows in MINOR.items():
        for r, (up, rev) in enumerate(rows):
            fid = f"{suit}_{r + 1:02d}" if r < 10 else f"{suit}_{r + 1}_{COURT_FILE[r - 10]}"
            cards.append({
                "id": fid, "en": f"{RANK_EN[r]} OF {SUIT_EN[suit]}", "ja": f"{SUIT_JA[suit]}の{RANK_JA[r]}",
                "up": up, "rev": rev, "major": False,
            })
    return cards


