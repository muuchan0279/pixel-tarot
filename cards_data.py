def _deg(lon: float) -> str:
    lon %= 360
    return f"{SIGN_JA[int(lon // 30)]}{int(lon % 30)}°"


def gd(cid: str) -> dict:
    """カードの対応。planet=惑星名 / signs=サイン番号の一覧 / zone=(始, 終)の黄経 / element / text=表示用"""
    out = {"planet": None, "signs": [], "zone": None, "element": None, "glyph": "", "text": ""}
    if cid.startswith("m"):
        heb, ch, kind, val = GD_MAJOR[int(cid[1:])]
        if kind == "planet":
            out.update(planet=val, glyph=PLANET_GLYPH[val], text=f"{heb} {ch} / {val}")
        elif kind == "sign":
            out.update(signs=[val], zone=(val * 30, val * 30 + 30), element=SIGN_ELEMENT[val],
                       glyph=SIGN_GLYPH[val], text=f"{heb} {ch} / {SIGN_JA[val]}")
        else:
            out.update(element=val, glyph=val, text=f"{heb} {ch} / 元素 {val}")
        return out
    suit, rest = cid.split("_", 1)
    el = SUIT_ELEMENT[suit]
    n = int(rest[:2])
    if n == 1:
        out.update(element=el, glyph=el, text=f"{el}の根源(エース)")
    elif n <= 10:
        sign = GD_DECAN_SIGNS[suit][(n - 2) // 3]
        dec = (n - 2) % 3
        ruler = DECAN_RULERS[sign][dec]
        z0 = sign * 30 + dec * 10
        out.update(planet=ruler, signs=[sign], zone=(z0, z0 + 10), element=el, glyph=PLANET_GLYPH[ruler],
                   text=f"{SIGN_JA[sign]}の第{dec + 1}デカン({dec * 10}°〜{dec * 10 + 10}°) / 支配星 {ruler}")
    else:
        court = rest.split("_")[1]
        cel = COURT_ELEMENT[court]
        out.update(element=el, glyph=el)
        if court == "page":
            out["text"] = f"{el}のなかの{cel}"
        else:
            s0 = GD_COURT_START[suit][["knight", "queen", "king"].index(court)]
            z0 = s0 * 30 + 20
            out.update(signs=[s0, (s0 + 1) % 12], zone=(z0, z0 + 30),
                       text=f"{el}のなかの{cel} / {_deg(z0)}〜{_deg(z0 + 30)}")
    return out


def in_zone(lon: float, zone) -> bool:
    z0, z1 = zone
    return (lon - z0) % 360 < (z1 - z0)


